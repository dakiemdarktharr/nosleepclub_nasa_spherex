def seed_for(field,wanted):
    text='sandwich-development.1|'+field+'|'+str(int(wanted['snr_per_frame']))+'|'+','.join(format(float(x),'.8g') for x in wanted['motion'])
    return str(int.from_bytes(sha256(text.encode('utf-8')).digest()[:8],'big'))


def seeds():
    return {field:{str(int(c['snr_per_frame'])):seed_for(field,c) for c in d.RULES['cases']} for field in d.RULES['fields']}


RULES={'version':'0.10.0-sandwich-development.1','fields':d.RULES['fields'],'cases':d.RULES['cases'],
       'patch_index':1,'draws_per_case':128,'noise_seeds':seeds(),
       'seed_derivation':'first 64 bits big-endian of SHA-256 of sandwich-development.1|field|integer_snr|motion components formatted .8g; stored as decimal string',
       'truth':'old nearest ePSF, fixed source amplitudes generated by frozen injected_frames',
       'noise':'fresh field/case PCG64 seeds; native independent Gaussian variance, paired across methods; no source shot noise',
       'point_estimator':'unchanged continuous padded target 0.10; 5 starts, 2 IRLS rounds, nuisance profiles and common single-source quality reference',
       'sandwich_rules':sandwich.RULES,'ellipse_thresholds':THRESHOLDS,'methods':METHODS,
       'mode_diagnostic':'five starts on fixed-final-weight objective, at the frozen point and nearby modes; no point replacement',
       'registration':'separate centroid-only and centroid-plus-registration; registration fixed in generator; no nominal total-coverage claim',
       'qualification':'three opened fields only; empirical fixed-final-IRLS sandwich, ten clusters typical, no derivative of robust weights, no physical PSF validation'}


def inputs():
    sources=['scripts/exposure_sandwich.py','scripts/run_sandwich_study.py','tests/test_exposure_sandwich.py','tests/test_continuous_epsf.py',
             'docs/SANDWICH_PROTOCOL.md','requirements.txt','scripts/continuous_epsf_model.py',
             'scripts/profile_uncertainty.py','scripts/diagnose_bias.py']+['scripts/'+v for v in d.study.sources()]
    products=['web/data/continuous-epsf/design.json','web/data/ablation/design.json']+[
        'web/data/ablation/validation-'+field+'.json' for field in RULES['fields']]
    return {s:d.digest(ROOT/s) for s in sources},{s:d.digest(ROOT/s) for s in products}


def create_design():
    if DESIGN.exists():raise RuntimeError('Refusing overwrite of design')
    baseline=json.loads(BIAS.read_text(encoding='utf-8'));continuous=json.loads(CONTINUOUS.read_text(encoding='utf-8'))
    if not baseline['completed'] or not continuous['completed']:raise RuntimeError('Baseline cache incomplete')
    if continuous['design_sha256']!=d.digest(ROOT/'web/data/continuous-epsf/design.json'):raise RuntimeError('Continuous design mismatch')
    flattened=[v for values in seeds().values() for v in values.values()]
    if len(set(flattened))!=len(flattened) or str(d.RULES['seed']) in flattened:raise RuntimeError('Noise seed collision')
    for field in RULES['fields']:
        baseline_field=next(v for v in baseline['fields'] if v['id']==field)
        for wanted in RULES['cases']:
            old=next(v for v in baseline_field['cases'] if v['patch_index']==1 and v['truth_psf']=='nearest' and v['snr_per_frame']==wanted['snr_per_frame'] and v['truth_delta_px']==wanted['motion'])
            if len(old['independent_gaussian_controls']['records'])!=64:raise RuntimeError('Previous control count mismatch')
    sources,products=inputs()
    doc={'rules':RULES,'source_hashes':sources,'opened_product_hashes':products,
         'baseline_sha256':d.digest(BIAS),'continuous_sha256':d.digest(CONTINUOUS),
         'status':'prospective opened-field covariance development, not validation'}
    DESIGN.parent.mkdir(parents=True,exist_ok=True)
    DESIGN.write_bytes((json.dumps(d.jsonable(doc),ensure_ascii=False,indent=2,allow_nan=False)+'\n').encode('utf-8'))
    print('DESIGN',DESIGN,d.digest(DESIGN),flush=True)


def verify_design():
    doc=json.loads(DESIGN.read_text(encoding='utf-8'));sources,products=inputs()
    if doc['rules']!=RULES or doc['source_hashes']!=sources or doc['opened_product_hashes']!=products:raise RuntimeError('Design/source/product mismatch')
    if doc['baseline_sha256']!=d.digest(BIAS) or doc['continuous_sha256']!=d.digest(CONTINUOUS):raise RuntimeError('Baseline cache hash mismatch')
    for path in [*sources,*products,DESIGN.relative_to(ROOT).as_posix()]:
        try:blob=subprocess.check_output(['git','show','HEAD:'+path],cwd=ROOT,stderr=subprocess.DEVNULL)
        except subprocess.CalledProcessError as exc:raise RuntimeError('Required source or design not committed: '+path) from exc
        if sha256(blob).hexdigest()!=d.digest(ROOT/path):raise RuntimeError('Uncommitted source/design change: '+path)
    return doc


def modes(fit,anchor):
    anchor=np.asarray(anchor,float);starts=[anchor]+[anchor+v for v in [(-.7,0),(.7,0),(0,-.7),(0,.7)]]
    residual=d.model.joint.residual_sample
    def cost(pos):
        r=np.concatenate([residual(s,pos) for s in fit['samples']]);return float(r@r)
    baseline_cost=cost(fit['position']);trials=[];distinct=[]
    for start in starts:
        try:
            value=d.model.old.solve(fit['samples'],anchor,starts=False,initial=start)
            row={'start_sky_px':start.tolist(),'success':bool(value.success),'position_sky_px':value.x.tolist(),
                 'delta_chi2_vs_fit':float(value.fun@value.fun-baseline_cost)}
            if value.success and all(np.linalg.norm(value.x-np.asarray(v))>.15 for v in distinct):distinct.append(value.x.tolist())
        except (ValueError,np.linalg.LinAlgError) as exc:row={'start_sky_px':start.tolist(),'success':False,'failure':type(exc).__name__}
        trials.append(row)
    return {'point_chi2':baseline_cost,'trials':trials,'distinct_modes_015px':len(distinct),
            'qualification':'post-fit fixed-final-weight objective; does not change the returned point or rerun IRLS'}


def method_covariances(fits,registration,error):
    transform=d.study.gaia.TRANSFORM;output={}
    for name in METHODS:
        if name=='gauss_newton':parts=[f['covariance'] for f in fits];reasons=[]
        elif name=='profile_hessian':
            reasons=[f['profile'].get('reason','unsupported_profile') for f in fits if not f['profile']['supported']]
            parts=[f['profile'].get('covariance_px2') for f in fits]
        else:
            reasons=[f['sandwich'].get('reason','unsupported_sandwich') for f in fits if not f['sandwich']['supported']]
            parts=[f['sandwich'].get('covariance_px2') for f in fits]
        if reasons:output[name]={'supported':False,'reasons':reasons};continue
        centroid=transform@sum(np.asarray(v) for v in parts)@transform.T
        total=transform@(sum(np.asarray(v) for v in parts)+registration)@transform.T
        if not sandwich.positive_full_rank(centroid) or not sandwich.positive_full_rank(total):
            output[name]={'supported':False,'reasons':['invalid_displacement_covariance']};continue
        output[name]={'supported':True,'centroid_only':{'covariance_arcsec2':centroid,'q':float(error@np.linalg.solve(centroid,error))},
                      'plus_registration':{'covariance_arcsec2':total,'q':float(error@np.linalg.solve(total,error))}}
    return output


def fit_pair(fs,catalog,xy,anchor,truth):
    try:
        references=[]
        for frames in fs:
            try:references.append(d.motion.fit_position(frames,np.asarray(anchor),multistart=True))
            except (ValueError,np.linalg.LinAlgError):references.append(None)
        fits=[candidate.fit(frames,catalog,xy,anchor,reference) for frames,reference in zip(fs,references)]
        for fit in fits:
            fit['sandwich']=sandwich.compute(fit)
            fit['mode_diagnostic']=modes(fit,anchor)
        transform=d.study.gaia.TRANSFORM
        error=transform@(fits[1]['position']-fits[0]['position']-truth)
        registration=sum(d.study.bench.registration_covariance(frames) for frames in fs)
        valid=all(candidate.numeric_valid(f) for f in fits)
        methods=method_covariances(fits,registration,error) if valid else {name:{'supported':False,'reasons':['invalid_point']} for name in METHODS}
        return {'numeric_valid':bool(valid),'accepted':bool(valid and all(f['quality']['accepted'] for f in fits)),
                'quality_reasons':sorted(set(sum([f['quality']['reasons'] for f in fits],[]))),
                'error_east_north_arcsec':error,'error_arcsec':float(np.linalg.norm(error)),
                'registration_covariance_sky_px2':registration,
                'epochs':[{**d.study.public(f),'profile':f['profile'],'sandwich':f['sandwich'],
                           'mode_diagnostic':f['mode_diagnostic']} for f in fits], 'methods':methods}
    except (ValueError,np.linalg.LinAlgError) as exc:
        return {'numeric_valid':False,'accepted':False,'failure':type(exc).__name__,'detail':str(exc),
                'methods':{name:{'supported':False,'reasons':['fit_exception']} for name in METHODS}}


def wilson(success,n):
    if n==0:return None
    z=1.959963984540054;p=success/n;den=1+z*z/n
    center=(p+z*z/(2*n))/den;half=z*np.sqrt(p*(1-p)/n+z*z/(4*n*n))/den
    return [float(max(0.,center-half)),float(min(1.,center+half))]


def summarize(rows):
    """All selections retain attempted and supported denominators explicitly."""
    result={'attempts':len(rows),'numeric':sum(bool(r.get('numeric_valid')) for r in rows),
            'accepted':sum(bool(r.get('accepted')) for r in rows),
            'fit_failures':sum('failure' in r for r in rows),
            'boundary_epochs':sum(bool(e.get('at_boundary')) for r in rows for e in r.get('epochs',[])),
            'multimode_epochs':sum(e['mode_diagnostic']['distinct_modes_015px']>1 for r in rows for e in r.get('epochs',[])),
            'mode_start_failures':sum(not t['success'] for r in rows for e in r.get('epochs',[]) for t in e['mode_diagnostic']['trials']),
            'lower_fixed_objective_epochs':sum(any(t.get('delta_chi2_vs_fit',0.) < -1e-4 for t in e['mode_diagnostic']['trials'])
                                               for r in rows for e in r.get('epochs',[]))}
    selectors={'all_attempts':lambda r:True,'numeric':lambda r:r.get('numeric_valid',False),
        'accepted':lambda r:r.get('accepted',False),
        'common_supported':lambda r:r.get('numeric_valid',False) and all(r['methods'][m]['supported'] for m in METHODS),
        'common_accepted':lambda r:r.get('accepted',False) and all(r['methods'][m]['supported'] for m in METHODS)}
    groups={}
    for label,select in selectors.items():
        selected=[r for r in rows if select(r)];valid=[r for r in selected if r.get('numeric_valid')]
        vectors=np.array([r['error_east_north_arcsec'] for r in valid],float).reshape((-1,2))
        errors=np.linalg.norm(vectors,axis=1)
        group={'attempts':len(selected),'numeric':len(valid),
               'bias_east_north_arcsec':vectors.mean(axis=0) if len(valid) else None,
               'rms_arcsec':float(np.sqrt(np.mean(errors**2))) if len(valid) else None,
               'p90_arcsec':float(np.percentile(errors,90)) if len(valid) else None,'methods':{}}
        for method in METHODS:
            available=[r['methods'][method] for r in valid if r['methods'][method]['supported']]
            reasons=[reason for r in valid if not r['methods'][method]['supported'] for reason in r['methods'][method].get('reasons',[])]
            stat={'supported':len(available),'unsupported':len(valid)-len(available),
                  'unsupported_reasons':{k:reasons.count(k) for k in sorted(set(reasons))}}
            for kind in ['centroid_only','plus_registration']:
                q=[a[kind]['q'] for a in available];cov=[np.asarray(a[kind]['covariance_arcsec2']) for a in available]
                coverage={}
                for level,threshold in THRESHOLDS.items():
                    inside=sum(v<=threshold for v in q)
                    coverage[level]={'inside':inside,'denominator':len(q),'fraction':inside/len(q) if q else None,'wilson_95':wilson(inside,len(q))}
                area=[float(np.pi*THRESHOLDS['68']*np.sqrt(np.linalg.det(v))) for v in cov]
                axis=[float(np.sqrt(THRESHOLDS['68']*np.linalg.eigvalsh(v).max())) for v in cov]
                stat[kind]={'coverage':coverage,'median_ellipse68_area_arcsec2':float(np.median(area)) if area else None,
                            'median_ellipse68_semimajor_arcsec':float(np.median(axis)) if axis else None,
                            'p90_ellipse68_semimajor_arcsec':float(np.percentile(axis,90)) if axis else None}
            group['methods'][method]=stat
        groups[label]=group
    result['selections']=groups
    return result


def save(report):
    OUTPUT.parent.mkdir(parents=True,exist_ok=True);tmp=OUTPUT.with_name(OUTPUT.name+'.tmp');d.save(tmp,report);tmp.replace(OUTPUT)


def run(fields,snrs):
    protocol=verify_design();design_hash=d.digest(DESIGN);base=json.loads(BIAS.read_text(encoding='utf-8'))
    if OUTPUT.exists():
        report=json.loads(OUTPUT.read_text(encoding='utf-8'))
        if report['completed']:raise RuntimeError('Completed report cannot be overwritten')
        if report['design_sha256']!=design_hash:raise RuntimeError('Existing report belongs to another design')
        for case in report['cases']:
            if [r['draw'] for r in case['records']]!=list(range(len(case['records']))) or len(case['records'])>RULES['draws_per_case']:raise RuntimeError('Invalid resume records')
    else:report={'design_sha256':design_hash,'rules':protocol['rules'],'cases':[],'completed':False}
    for ident in fields:
        print('LOAD',ident,flush=True)
        _,_,catalog,xy,before,after,source=d.load_field(ident)
        oldfield=next(v for v in base['fields'] if v['id']==ident)
        for wanted in RULES['cases']:
            if wanted['snr_per_frame'] not in snrs:continue
            oldcase=next(v for v in oldfield['cases'] if v['snr_per_frame']==wanted['snr_per_frame'] and v['truth_delta_px']==wanted['motion'])
            anchor=oldcase['anchor'];truth=np.asarray(wanted['motion']);snr=wanted['snr_per_frame']
            case=next((v for v in report['cases'] if v['field']==ident and v['snr_per_frame']==snr),None)
            if case is None:
                case={'field':ident,'source':source,'snr_per_frame':snr,'anchor_sky_px':anchor,
                      'truth_delta_sky_px':truth,'noise_seed':RULES['noise_seeds'][ident][str(int(snr))],'records':[]}
                report['cases'].append(case)
            planted=d.study.injected_frames(before,after,anchor,truth,snr,'nearest')
            if 'original_background' not in case:
                case['original_background']={'frozen_baseline':oldcase['frozen_result'],'candidate':fit_pair(planted,catalog,xy,anchor,truth)};save(report)
            signals=[[{**a,'data':a['data']-o['data']} for a,o in zip(added,original)] for added,original in zip(planted,[before,after])]
            rng=np.random.default_rng(int(case['noise_seed']))
            for draw in range(RULES['draws_per_case']):
                fs=[[{**f,'data':f['data']+rng.normal(size=f['data'].shape)*np.sqrt(f['variance'])} for f in frames] for frames in signals]
                if draw<len(case['records']):continue
                row=fit_pair(fs,catalog,xy,anchor,truth);row['draw']=draw;case['records'].append(row)
                case['summary']=summarize(case['records']);save(report)
                print('DRAW',ident,snr,draw+1,flush=True)
    report['completed']=len(report['cases'])==len(RULES['fields'])*len(RULES['cases']) and all(len(c['records'])==RULES['draws_per_case'] and 'original_background' in c for c in report['cases'])
    save(report);print('COMPLETED',report['completed'],flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__);group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--design',action='store_true');group.add_argument('--run',action='store_true')
    parser.add_argument('--fields',nargs='+',choices=RULES['fields'],default=RULES['fields'])
    parser.add_argument('--snrs',nargs='+',choices=[2.,4.],type=float,default=[2.,4.])
    args=parser.parse_args()
    if args.design:create_design()
    else:run(args.fields,args.snrs)


if __name__=='__main__':main()
